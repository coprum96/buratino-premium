export function getAssessmentItems(wave: 'immediate' | 'delayed'): AssessmentItem[] {
  return assessmentBank.filter((item) => item.wave === wave);
}

export function toQuizQuestions(wave: 'immediate' | 'delayed') {
  return getAssessmentItems(wave).map((item) => ({
    id: item.id,
    text: item.text,
    options: item.options,
    correct: item.correct,
    explanation: item.explanation,
  }));
}
