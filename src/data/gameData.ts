// Types
export interface Character {
  name: string;
  emoji: string;
  image?: string;
  emotions?: Record<string, string>;
}

export interface ChoiceAftermathOverride {
  signal?: string;
  confirms?: string;
  doesNotProve?: string;
  nextStep?: string;
  relation?: string;
}

export interface Choice {
  text: string;
  icon: string;
  id?: string;
  detail?: string;
  wisdom?: number;
  coins?: number;
  next?: number;
  nextLevel?: boolean;
  nextPhase?: string;
  feedback?: string;
  consequence?: 'safe' | 'risky' | 'loss' | 'pause' | 'check';
  evidence?: string[];
  flags?: string[];
  aftermath?: ChoiceAftermathOverride;
}

export interface Dialogue {
  character: string;
  emotion?: string;
  text: string;
  redFlags?: string[];
  redFlagsData?: RedFlagDetail[];
  choices: Choice[];
  presentation?: PresentationSlide[];
  microscope?: MicroscopeData;
  pressureTimer?: number; // секунды для таймера давления
  calculator?: boolean; // показать калькулятор потерь
  matchGame?: boolean; // показать игру сопоставления
  siteCompare?: boolean;
  lieDetector?: LieDetectorData;
  question?: string;
  variants?: Partial<Record<'safe' | 'pause' | 'loss' | 'risky' | 'check', { text: string }>>;
}

export function infoNote(title: string, description: string): RedFlagDetail {
  return { title, description };
}

export interface RedFlagDetail {
  title: string;
  description: string;
  example?: string;
  law?: string;
  statistics?: string;
  video?: string;
  tips?: string[];
}

export interface LieDetectorData {
  character: string;
  segments: LieSegment[];
}

export interface LieSegment {
  text: string;
  isLie: boolean;
  explanation?: string;
}

export interface PresentationSlide {
  title: string;
  content: string;
  image?: string;
  redFlags?: string[];
}

export interface MicroscopeData {
  title: string;
  smallPrintText: string;
  dangerousTerms?: { term: string; explanation: string }[];
}

export interface QuizQuestion {
  id?: string;
  text: string;
  options: string[];
  correct: number;
  explanation?: string;
  reward?: number;
}

export interface Level {
  id: number;
  title: string;
  subtitle: string;
  gradient: string;
  dialogues: Dialogue[];
  quiz: QuizQuestion[];
  miniGame?: string;
}

export interface ScenarioTestItem {
  text: string;
  correct: number;
  reward: number;
}

export interface EducationalSection {
  name: string;
  content: string;
}

export interface EducationalMaterial {
  id: number;
  title: string;
  sections: EducationalSection[];
}

