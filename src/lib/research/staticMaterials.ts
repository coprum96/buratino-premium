import { CHAPTER_META, TOTAL_GAME_DURATION_MIN } from '../../data/learningStages';

export function exportComparisonMaterials(): string {
  const topics = CHAPTER_META.map((chapter) => [
    `## ${chapter.title}`,
    `Цель: ${chapter.goal}`,
    `Ориентир по времени: ${chapter.durationMin} минут.`,
    '',
    'Кратко:',
    '- Какие признаки давления и нереалистичной доходности встречаются в объявлениях.',
    '- Чем зарегистрированная компания отличается от добросовестной сделки.',
    '- Почему телесный дискомфорт — повод проверить факты, а не детектор лжи.',
    '- Какие шаги нужны, если перевод уже ушёл.',
    '',
  ].join('\n'));

  return [
    '# Информационные материалы для группы сравнения',
    '',
    `Ориентир по продолжительности всей игры: ${TOTAL_GAME_DURATION_MIN} минут.`,
    'Этот текст покрывает те же темы, но без интерактивного выбора решений.',
    '',
    ...topics,
    '## Источники для самостоятельной проверки',
    '- Сайт Банка России и раздел о мошенничестве: https://www.cbr.ru',
    '- Реестры участников финансового рынка Банка России.',
    '- АСВ: система страхования вкладов, https://www.asv.org.ru',
    '- Интернет-приёмная Банка России для обращений.',
    '',
    'Дата подготовки материалов: октябрь 2026. Цифры доходности и ставок нужно сверять на дату чтения.',
  ].join('\n');
}
