import type { FinaleDecision } from './scoring';

export type EndingId = 'safe' | 'pause' | 'loss';

export interface EndingContent {
  id: EndingId;
  title: string;
  summary: string;
  coinsNote: string;
  actions: string[];
  tone: 'success' | 'caution' | 'danger';
}

export interface EndingInput {
  finaleDecision: FinaleDecision | null;
  coins: number;
  lostAllCoins: boolean;
}

export function resolveEnding(input: EndingInput): EndingId {
  if (input.finaleDecision === 'loss' || input.lostAllCoins || input.coins <= 0) {
    return 'loss';
  }
  if (input.finaleDecision === 'pause') {
    return 'pause';
  }
  return 'safe';
}

export function getEndingContent(endingId: EndingId, coins: number): EndingContent {
  if (endingId === 'loss') {
    return {
      id: 'loss',
      title: 'Деньги уже ушли. Теперь важны действия',
      summary: 'Ты перевёл монеты по рискованному предложению. Это не победа и не «монеты в безопасности». Сейчас нужна не паника, а точный порядок шагов.',
      coinsNote: `Сейчас у тебя ${coins} монет. Если перевод уже прошёл, вернуть деньги быстро получается не всегда.`,
      tone: 'danger',
      actions: [
        'Сразу прекрати новые переводы и не «догоняй» сумму.',
        'Позвони в банк или платёжный сервис и попроси заблокировать операцию и карту, если данные могли уйти.',
        'Сохрани переписку, чеки, сайт, реквизиты и имена. Скриншоты тоже считаются.',
        'Обратись в полицию и напиши заявление о мошенничестве.',
        'Сообщи в Банк России через интернет-приёмную и, если нужно, на госуслуги.',
        'Предупреди близких: по этой же схеме могут позвонить им.',
      ],
    };
  }

  if (endingId === 'pause') {
    return {
      id: 'pause',
      title: 'Ты поставил паузу. Это сильное решение',
      summary: 'Ты не купился на срочность и оставил время на проверку. Сомнение здесь не слабость, а рабочий навык.',
      coinsNote: `Монеты пока при тебе: ${coins}. Это не значит, что предложение уже проверено.`,
      tone: 'caution',
      actions: [
        'Проверь компанию в официальных реестрах, а не только на её сайте.',
        'Спроси человека, который не получает выгоду от сделки.',
        'Сравни обещанную доходность с обычными инструментами и спроси, откуда берётся прибыль.',
        'Если данных мало, не заполняй пробелы догадками — это повод не переводить деньги.',
      ],
    };
  }

  return {
    id: 'safe',
    title: 'Ты не отдал деньги незнакомцам',
    summary: 'Ты заметил давление, нереалистичную доходность и отказ объяснить механизм. Монеты остались у тебя не случайно.',
    coinsNote: `Сохранено монет: ${coins}. Это следствие твоего решения, а не автоматическая награда за тест.`,
    tone: 'success',
    actions: [
      'Оставь привычку задавать четыре вопроса Золотого Детектора.',
      'Не путай регистрацию компании с её добросовестностью.',
      'Сложные или доходные условия сами по себе не равны мошенничеству — проверяй совокупность признаков.',
    ],
  };
}
