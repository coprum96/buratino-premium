import { strongEvidenceCount } from './evidence';
import type { FinaleDecision } from './scoring';

export type EndingId = 'golden' | 'saved' | 'costly' | 'trapped' | 'falseAlarm';

export interface EndingContent {
  id: EndingId;
  title: string;
  summary: string;
  coinsNote: string;
  actions: string[];
  tone: 'success' | 'caution' | 'danger';
  report: {
    good: string;
    almost: string;
    missed: string;
    turningPoint: string;
    checkNext: string;
    skill: string;
  };
}

export interface EndingInput {
  finaleDecision: FinaleDecision | null;
  coins: number;
  lostAllCoins: boolean;
  evidenceFound?: string[];
  storyFlags?: string[];
}

export function resolveEnding(input: EndingInput): EndingId {
  const flags = input.storyFlags ?? [];
  const strong = strongEvidenceCount(input.evidenceFound ?? []);

  if (flags.includes('false-alarm')) return 'falseAlarm';
  if (input.finaleDecision === 'loss' || input.lostAllCoins || input.coins <= 0) return 'trapped';
  if (input.coins < 5 && strong >= 3) return 'costly';
  if (input.coins >= 4 && strong >= 4 && input.finaleDecision !== 'pause') return 'golden';
  return 'saved';
}

